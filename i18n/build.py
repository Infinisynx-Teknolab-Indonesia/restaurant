"""Bangun file kamus terjemahan dari part*.txt:
  - packages/resto_core/lib/src/i18n_data.dart  (aplikasi Flutter)
  - vps/server/admin_web/i18n.js + pc/server/admin_web/i18n.js (admin panel)
Jalankan: python i18n/build.py
Bisa dijalankan dari paket Server maupun paket Flutter — file yang foldernya tidak ada dilewati.
Kalau teks diubah, salin folder i18n/ ke kedua paket supaya kamusnya sama.
"""
import glob, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

PHRASES = [  # fallback kata per kata (dipakai bila kalimat utuh tidak ada di kamus)
    ("mnt lalu", "min ago", "分钟前"), ("jam lalu", "h ago", "小时前"), ("baru saja", "just now", "刚刚"),
    ("siap diantar", "ready to serve", "可以上菜"), ("Belum bayar", "Unpaid", "未付款"),
    ("Meja ", "Table ", "桌 "), (" poin", " points", " 积分"), ("Lunas", "Paid", "已付款"),
]


def load():
    d = {}
    for f in sorted(glob.glob(os.path.join(HERE, "part*.txt"))):
        for n, line in enumerate(open(f, encoding="utf-8"), 1):
            line = line.rstrip("\n")
            if not line.strip() or line.lstrip().startswith("#"):
                continue
            parts = line.split(" || ")
            if len(parts) != 3:
                raise SystemExit(f"{f}:{n}: format salah → {line}")
            k, en, zh = (p.replace("\\n", "\n") for p in parts)
            if k.strip() != k and not k.startswith(" "):
                k = k.strip()
            if k.count("{}") != en.count("{}") or k.count("{}") != zh.count("{}"):
                raise SystemExit(f"{f}:{n}: jumlah {{}} tidak sama → {line}")
            d.setdefault(k, (en, zh))
    return d


def dart_str(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$").replace("\n", "\\n") + "'"


def main():
    d = load()
    lines = ["// GENERATED by i18n/build.py — jangan edit manual, edit i18n/part*.txt lalu jalankan build.py",
             "// ignore_for_file: lines_longer_than_80_chars", "",
             "/// Kamus: teks Indonesia → [English, 中文]. `{}` = bagian dinamis.",
             "const Map<String, List<String>> kTr = {"]
    for k in sorted(d):
        en, zh = d[k]
        lines.append(f"  {dart_str(k)}: [{dart_str(en)}, {dart_str(zh)}],")
    lines += ["};", "", "/// Fallback kata per kata: [Indonesia, English, 中文].", "const List<List<String>> kPhrases = ["]
    for p in PHRASES:
        lines.append("  [" + ", ".join(dart_str(x) for x in p) + "],")
    lines.append("];")
    dart = os.path.join(ROOT, "packages/resto_core/lib/src/i18n_data.dart")
    if os.path.isdir(os.path.dirname(dart)):  # paket Flutter
        open(dart, "w", encoding="utf-8").write("\n".join(lines) + "\n")

    engine = open(os.path.join(HERE, "admin_i18n_engine.js"), encoding="utf-8").read()
    js = ("/* GENERATED by i18n/build.py — kamus admin (Indonesia → English / 中文) */\n"
          "window.RB_I18N_DICT = " + json.dumps({k: list(v) for k, v in sorted(d.items())}, ensure_ascii=False, separators=(",", ":")) + ";\n"
          + "window.RB_I18N_PHRASES = " + json.dumps(PHRASES, ensure_ascii=False) + ";\n" + engine)
    for side in ("vps", "pc"):
        p = os.path.join(ROOT, side, "server/admin_web/i18n.js")
        if os.path.isdir(os.path.dirname(p)):
            open(p, "w", encoding="utf-8").write(js)
    print(f"{len(d)} entri kamus → i18n_data.dart + admin_web/i18n.js")


if __name__ == "__main__":
    main()
